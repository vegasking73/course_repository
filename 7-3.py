a = 10
b = 3

print(a // b)  # 3 - Deler a på b og runder ned til nærmeste heltal
print(type(a // b))  # <class 'int'> - Resultatet av heltallsdeling er alltid en int

print(a % b)  # 1 - Resten etter deling av a på b
print(type(a % b))  # <class 'int'> - Resultatet av modulus er alltid en int

print(7 % 2)  # 1 - Resten etter deling av 7 på 2
print(8 % 2)  # 0 - Resten etter deling av 8 på 2
print(9 % 2)  # 1 - Resten etter deling av 9 på 2

